_BOLD = re.compile(r"\*\*(.+?)\*\*")


def visible(user) -> list[dict]:
    out = []
    for a in ARTICLES:
        if a.get("role") and not (user.role == a["role"] or user.is_super_admin):
            continue
        if a["perms"] and not user.is_super_admin and not any(user.can(p) for p in a["perms"]):
            continue
        out.append(a)
    return out


def plain(a: dict) -> str:
    """All of a guide's words, lower-case, for searching."""
    return _BOLD.sub(r"\1", " ".join([a["title"], a["cat"], a["keys"], *a["steps"], *a["tips"]])).lower()


def search(items: list[dict], q: str) -> list[dict]:
    words = [w for w in re.split(r"\s+", (q or "").lower().strip()) if w and w not in ("how", "to", "do", "i", "a", "the", "paano", "mag")]
    if not words:
        return items
    scored = []
    for a in items:
        text, title = plain(a), (a["title"] + " " + a["keys"]).lower()
        if all(w in text for w in words):
            scored.append((-sum(2 if w in title else 1 for w in words), a))
    return [a for _, a in sorted(scored, key=lambda x: x[0])]


def bold(text: str):
    """Escape, then show **button names** in bold."""
    from markupsafe import Markup, escape
    return Markup(_BOLD.sub(r"<strong>\1</strong>", str(escape(text))))
